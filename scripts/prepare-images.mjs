const exists = async (p) => {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
};

const entries = [];

for (const item of PLAN) {
  const target = join(dir, `${item.slug}.jpg`);
  const source = join(dir, item.from);

  if (!(await exists(target)) && (await exists(source))) {
    await rename(source, target);
    console.log(`  → ${item.slug}.jpg`);
  }

  const info = await sharp(target).metadata();
  const oriented = (info.orientation ?? 1) >= 5;
  const width = oriented ? info.height : info.width;
  const height = oriented ? info.width : info.height;

  const blur = await sharp(target).rotate().resize(12).jpeg({ quality: 45 }).toBuffer();

  entries.push({
    slug: item.slug,
    src: `/images/${item.slug}.jpg`,
    width,
    height,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
    alt: item.alt,
  });
}

const body = entries
  .map(
    (e) => `  "${e.slug}": {
    src: "${e.src}",
    width: ${e.width},
    height: ${e.height},
    alt: ${JSON.stringify(e.alt)},
    blurDataURL:
      "${e.blurDataURL}",
  },`
  )
  .join("\n");

const file = `// AUTO-GENERATED by scripts/prepare-images.mjs — do not edit by hand.
// Dimensions and blur placeholders are read from the files in public/images.

export interface ImageAsset {
  /** Public URL, e.g. "/images/living-linear-cove.jpg". */
  src: string;
  width: number;
  height: number;
  /** Default accessible description; override at the call site when needed. */
  alt: string;
  /** Tiny inline JPEG used as the blur-up placeholder. */
  blurDataURL: string;
}

export const IMAGES = {
${body}
} satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof IMAGES;
`;

await writeFile(manifestPath, file, "utf8");
console.log(`\nWrote ${entries.length} entries to src/lib/image-manifest.ts`);
